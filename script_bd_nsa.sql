-- Fazer o script de criação do Banco de Dados com base na imagem DA MODELAGEM em anexo;

CREATE DATABASE BD_NSA;
USE BD_NSA;

CREATE TABLE tb_curso (
    cd_curso   INT PRIMARY KEY,
    nm_curso   VARCHAR(45) NOT NULL
);

CREATE TABLE tb_turma (
    cd_turma      VARCHAR(4) PRIMARY KEY,
    nm_periodo    VARCHAR(20) NOT NULL,
    nr_modulo     INT NOT NULL,
    nr_grupo      CHAR(1) NOT NULL,
    fk_cd_curso   INT NOT NULL,
    CONSTRAINT fk_turma_curso
	FOREIGN KEY (fk_cd_curso) REFERENCES tb_curso (cd_curso)
);

CREATE TABLE tb_aluno (
    rm_aluno       INT PRIMARY KEY,
    nm_aluno       VARCHAR(45) NOT NULL,
    fk_cd_turma    VARCHAR(4) NOT NULL,
    CONSTRAINT fk_aluno_turma
	FOREIGN KEY (fk_cd_turma) REFERENCES tb_turma (cd_turma)
);

CREATE TABLE tb_componente_curricular (
    cd_componente   INT PRIMARY KEY,
    nm_componente   VARCHAR(45) NOT NULL,
    qt_aulas        INT NOT NULL,
    id_pratica      BIT NOT NULL,
    fk_cd_turma     VARCHAR(4) NOT NULL,
    CONSTRAINT fk_componente_turma
	FOREIGN KEY (fk_cd_turma) REFERENCES tb_turma (cd_turma)
);

CREATE TABLE tb_atividade (
    cd_atividade      INT PRIMARY KEY,
    nm_atividade      VARCHAR(45) NOT NULL,
    dt_entrega        DATE NOT NULL,
    fk_cd_componente  INT NOT NULL,
    CONSTRAINT fk_atividade_componente
	FOREIGN KEY (fk_cd_componente) REFERENCES tb_componente_curricular (cd_componente)
);

CREATE TABLE tb_nota (
    cd_nota          INT PRIMARY KEY,
    fk_rm_aluno      INT NOT NULL,
    fk_cd_atividade  INT NOT NULL,
    vl_nota          DECIMAL(3,1) NOT NULL,
    CONSTRAINT fk_nota_aluno
	FOREIGN KEY (fk_rm_aluno) REFERENCES tb_aluno (rm_aluno),
    CONSTRAINT fk_nota_atividade
	FOREIGN KEY (fk_cd_atividade) REFERENCES tb_atividade (cd_atividade)
);

CREATE TABLE tb_professor (
    rm_professor    INT PRIMARY KEY,
    nm_professor   VARCHAR(45) NOT NULL,
    nm_formacao    VARCHAR(45) NOT NULL
);

CREATE TABLE tb_docencia (
    cd_docencia        INT PRIMARY KEY,
    nr_grupo           CHAR(1) NOT NULL,
    fk_rm_professor    INT NOT NULL,
    fk_cd_componente   INT NOT NULL,
    CONSTRAINT fk_docencia_professor
	FOREIGN KEY (fk_rm_professor) REFERENCES tb_professor (rm_professor),
    CONSTRAINT fk_docencia_componente
	FOREIGN KEY (fk_cd_componente) REFERENCES tb_componente_curricular (cd_componente)
);

